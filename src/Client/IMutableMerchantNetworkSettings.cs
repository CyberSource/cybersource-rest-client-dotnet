using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Net;
using System.Net.Http;
using System.Text;
using System.Text.Json;
using System.Threading.Tasks;
using CyberSource.Utilities.Serialization;

namespace CyberSource.Client
{
    /// <summary>
    /// Defines the internal, mutable contract for merchant network settings, extending <see cref="IMerchantNetworkSettings"/>
    /// with setter methods that allow the network configuration to be updated after construction.
    /// </summary>
    internal interface IMutableMerchantNetworkSettings : IMerchantNetworkSettings
    {
        /// <summary>
        /// Sets the default developer ID to be included in API requests for tracking and attribution.
        /// </summary>
        /// <param name="value">The default developer ID to include in API requests.</param>
        void SetDefaultDeveloperId(string value);

        /// <summary>
        /// Sets a value indicating whether to use a proxy server for HTTP requests.
        /// </summary>
        /// <param name="value"><c>"true"</c> to use a proxy server for HTTP requests; otherwise, <c>"false"</c>.</param>
        void SetUseProxy(string value);

        /// <summary>
        /// Sets the address or hostname of the proxy server to use for HTTP requests.
        /// </summary>
        /// <param name="value">The address or hostname of the proxy server.</param>
        void SetProxyAddress(string value);

        /// <summary>
        /// Sets the port number of the proxy server to use for HTTP requests.
        /// </summary>
        /// <param name="value">The port number of the proxy server.</param>
        void SetProxyPort(string value);

        /// <summary>
        /// Sets the username for authenticating with the proxy server, if required.
        /// </summary>
        /// <param name="value">The username for authenticating with the proxy server.</param>
        void SetProxyUsername(string value);

        /// <summary>
        /// Sets the password for authenticating with the proxy server, if required.
        /// </summary>
        /// <param name="value">The password for authenticating with the proxy server.</param>
        void SetProxyPassword(string value);

        /// <summary>
        /// Sets the configured <see cref="WebProxy"/> instance used for HTTP requests.
        /// </summary>
        /// <param name="value">The <see cref="WebProxy"/> instance to use for HTTP requests.</param>
        void SetProxy(WebProxy value);

        /// <summary>
        /// Sets the HTTP connection timeout in milliseconds.
        /// </summary>
        /// <param name="value">The HTTP connection timeout in milliseconds.</param>
        void SetTimeOut(int value);

        /// <summary>
        /// Sets the maximum number of connections to maintain in the connection pool.
        /// </summary>
        /// <param name="value">The maximum number of connections to maintain in the connection pool.</param>
        void SetMaxConnectionPoolSize(string value);

        /// <summary>
        /// Sets the time in seconds to keep idle connections alive before closing them.
        /// </summary>
        /// <param name="value">The time in seconds to keep idle connections alive before closing them.</param>
        void SetKeepAliveTime(string value);

        /// <summary>
        /// Sets the target endpoint or URI path for the CyberSource API request.
        /// </summary>
        /// <param name="value">The target endpoint or URI path for the CyberSource API request.</param>
        void SetRequestTarget(string value);

        /// <summary>
        /// Sets the JSON-formatted request payload data to be sent in the API request body.
        /// </summary>
        /// <param name="value">The JSON-formatted request payload data to send in the API request body.</param>
        void SetRequestJsonData(string value);

        /// <summary>
        /// Sets the type of HTTP request method to be used (e.g., POST, PUT, GET, PATCH).
        /// </summary>
        /// <param name="value">The type of HTTP request method to use (e.g., POST, PUT, GET, PATCH).</param>
        void SetRequestType(string value);

        /// <summary>
        /// Sets the SDK client identifier used to track SDK usage and version information in API requests.
        /// </summary>
        /// <param name="value">The SDK client identifier used to track SDK usage and version information.</param>
        void SetSdkClientId(string value);

        /// <summary>
        /// Sets a value indicating whether the code was generated by MCP.
        /// When <c>true</c>, SDK telemetry headers (v-c-sdk-telemetry-merchant-id and v-c-sdk-telemetry-mcp) will be sent with API requests.
        /// </summary>
        /// <param name="value"><c>true</c> if the code was generated by MCP; otherwise, <c>false</c>.</param>
        void SetIsSDK(bool value);

        /// <summary>
        /// Sets the logger instance used for logging network configuration and validation messages.
        /// </summary>
        /// <param name="value">The <see cref="Logger"/> instance used for logging.</param>
        void SetLogger(ILogger value);

        /// <summary>
        /// Sets the JSON serializer options used to serialize request payloads sent to the CyberSource API.
        /// </summary>
        /// <param name="value">The <see cref="JsonSerializerOptions"/> used to serialize request payloads.</param>
        void SetSerializationOptions(JsonSerializerOptions value);

        /// <summary>
        /// Sets the JSON serializer options used to deserialize response payloads returned from the CyberSource API.
        /// </summary>
        /// <param name="value">The <see cref="JsonSerializerOptions"/> used to deserialize response payloads.</param>
        void SetDeserializationOptions(JsonSerializerOptions value);

        /// <summary>
        /// Sets the caller-supplied <see cref="System.Net.Http.HttpClient"/> that RestSharp should use for outgoing requests.
        /// Passing <c>null</c> restores the SDK-managed HttpClient behavior (either via <see cref="IMerchantNetworkSettings.HttpClientFactory"/>
        /// or the internally cached <see cref="StandardSocketsHttpHandler"/>-backed client).
        /// The SDK never disposes the supplied client; its lifetime is entirely owned by the caller.
        /// </summary>
        /// <param name="value">The caller-owned <see cref="System.Net.Http.HttpClient"/> instance to use, or <c>null</c> to clear.</param>
        void SetHttpClient(HttpClient value);

        /// <summary>
        /// Sets the caller-supplied <see cref="System.Net.Http.IHttpClientFactory"/> used to resolve an <see cref="System.Net.Http.HttpClient"/>
        /// per request. Only consulted when <see cref="IMerchantNetworkSettings.HttpClient"/> is <c>null</c>.
        /// </summary>
        /// <param name="value">The <see cref="System.Net.Http.IHttpClientFactory"/> instance to use, or <c>null</c> to clear.</param>
        void SetHttpClientFactory(IHttpClientFactory value);

        /// <summary>
        /// Appends a consumer-supplied post-configure callback to
        /// <see cref="IMerchantNetworkSettings.SerializationPostConfigures"/>. Callbacks are
        /// invoked in insertion order at <see cref="CyberSource.Client.ApiClient"/> construction
        /// time, before the SDK's mandatory serialization invariants are applied.
        /// </summary>
        /// <param name="postConfigure">The callback to append; a <c>null</c> value is ignored.</param>
        void AddSerializationPostConfigure(Action<JsonSerializerOptions> postConfigure);

        /// <summary>
        /// Appends a consumer-supplied post-configure callback to
        /// <see cref="IMerchantNetworkSettings.DeserializationPostConfigures"/>. Callbacks are
        /// invoked in insertion order at <see cref="CyberSource.Client.ApiClient"/> construction
        /// time, before the SDK's mandatory deserialization invariants are applied.
        /// </summary>
        /// <param name="postConfigure">The callback to append; a <c>null</c> value is ignored.</param>
        void AddDeserializationPostConfigure(Action<JsonSerializerOptions> postConfigure);

        /// <summary>
        /// Sets the DI-resolved <see cref="IOptionsMonitor{TOptions}"/> for the SDK-owned
        /// <see cref="SdkSerializerOptions"/> wrapper. When set, the SDK reads
        /// <c>CurrentValue.Options</c> at <see cref="CyberSource.Client.ApiClient"/> construction
        /// and ignores any direct <see cref="IMerchantNetworkSettings.SerializationOptions"/> /
        /// <see cref="IMerchantNetworkSettings.SerializationPostConfigures"/> values.
        /// </summary>
        /// <param name="value">The monitor instance to use, or <c>null</c> to clear.</param>
        void SetSerializerOptionsMonitor(IOptionsMonitor<SdkSerializerOptions> value);

        /// <summary>
        /// Sets the DI-resolved <see cref="IOptionsMonitor{TOptions}"/> for the SDK-owned
        /// <see cref="SdkDeserializerOptions"/> wrapper. When set, the SDK reads
        /// <c>CurrentValue.Options</c> at <see cref="CyberSource.Client.ApiClient"/> construction
        /// and ignores any direct <see cref="IMerchantNetworkSettings.DeserializationOptions"/> /
        /// <see cref="IMerchantNetworkSettings.DeserializationPostConfigures"/> values.
        /// </summary>
        /// <param name="value">The monitor instance to use, or <c>null</c> to clear.</param>
        void SetDeserializerOptionsMonitor(IOptionsMonitor<SdkDeserializerOptions> value);
    }
}
